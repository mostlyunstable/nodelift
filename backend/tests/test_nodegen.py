# ruff: noqa: E501
import asyncio
import textwrap
from typing import Any

import pytest

from app.explorer.nodegen import NotConvertible, build_draft
from app.runtime.subprocess_runner import SubprocessRunner

ORIGIN = "octo/hello@abc1234 calc.py:3 (total)"

MODULE = textwrap.dedent(
    '''
    import json
    import math
    import requests
    from collections import Counter, OrderedDict
    from . import sibling

    TAX = 0.2
    UNUSED = 5

    def helper(x):
        return round(x * (1 + TAX), 2)

    class Box:
        def __init__(self, v):
            self.v = v

    @staticmethod_like
    def decorated(x):
        return x

    def total(items, discount=0):
        """Sum with tax."""
        c = Counter(i["kind"] for i in items)
        t = sum(helper(i["price"]) for i in items) - discount
        return {"total": round(t, 2), "kinds": dict(c), "sqrt": math.sqrt(4), "box": Box(1).v}

    def one(x):
        return json.dumps({"x": x})

    async def acoro(a):
        return a + 1

    def uses_missing():
        return GLOBAL_THING + sibling.x + requests.get("x")
    '''
)


def run_source(source: str, data: Any) -> Any:
    res = asyncio.run(SubprocessRunner(sandbox_mode="auto").run(source, data, 10))
    assert res.error is None, (res.error, source)
    return res.output


def test_copies_the_function_with_its_closure_and_only_what_it_uses() -> None:
    d = build_draft(MODULE, "total", ORIGIN)
    names = {(c["kind"], c["name"]) for c in d.copied}
    assert names == {
        ("import", "math"),
        ("import", "Counter"),
        ("constant", "TAX"),
        ("function", "helper"),
        ("class", "Box"),
        ("function", "total"),
    }
    assert (
        "UNUSED" not in d.source and "import json" not in d.source and "OrderedDict" not in d.source
    )
    assert (
        "from collections import Counter" in d.source and "OrderedDict" not in d.source
    )  # pruned to the used name
    assert d.source.startswith(f"# Copied from {ORIGIN}\n# Generated by Nodecraft")
    assert d.params == ["items", "discount"]


def test_the_generated_node_really_runs_and_gives_the_same_answer_as_the_original() -> None:
    d = build_draft(MODULE, "total", ORIGIN)
    items = [{"kind": "a", "price": 10}, {"kind": "a", "price": 5}, {"kind": "b", "price": 1}]
    out = run_source(d.source, {"items": items, "discount": 1})  # fields become keyword arguments
    ns: dict[str, Any] = {}
    exec(  # the reference: the same code run directly in this test process
        "import math\nfrom collections import Counter\nTAX = 0.2\n"
        + "def helper(x):\n    return round(x * (1 + TAX), 2)\nclass Box:\n    def __init__(self, v):\n        self.v = v\n"
        + "def total(items, discount=0):\n    c = Counter(i['kind'] for i in items)\n    t = sum(helper(i['price']) for i in items) - discount\n    return {'total': round(t, 2), 'kinds': dict(c), 'sqrt': math.sqrt(4), 'box': Box(1).v}\n",
        ns,
    )
    assert out == ns["total"](items, 1)


def test_single_argument_functions_receive_the_whole_input() -> None:
    d = build_draft(MODULE, "one", ORIGIN)
    assert "return one(input_data)" in d.source
    assert run_source(d.source, {"a": 1}) == '{"x": {"a": 1}}'


def test_async_functions_are_run_to_completion() -> None:
    d = build_draft(MODULE, "acoro", ORIGIN)
    assert "asyncio.run(acoro(input_data))" in d.source
    assert run_source(d.source, 41) == 42


def test_what_cannot_be_copied_is_reported_not_hidden() -> None:
    d = build_draft(MODULE, "uses_missing", ORIGIN)
    text = "\n".join(d.warnings)
    assert "`GLOBAL_THING` is used but could not be found" in text
    assert "`import requests` needs `requests`, which is not in the Python standard library" in text
    assert "imports another file of the repository" in text and "sibling" in text
    assert (
        "# unavailable in a code node: import requests" in d.source
    )  # kept visible, but cannot break loading
    assert d.free_names == ["GLOBAL_THING"]


def test_unavailable_imports_do_not_stop_the_rest_from_working() -> None:
    src = "from .compat import Mapping, str\nfrom typing import Any\n\ndef f(v: Mapping[Any, Any] | None) -> dict[Any, Any]:\n    return dict(v or {}) if not isinstance(v, str) else {}\n"
    d = build_draft(src, "f", ORIGIN)
    assert d.source.index("from __future__ import annotations") < d.source.index("def f(")
    assert run_source(d.source, [["a", 1]]) == {
        "a": 1
    }  # runs although Mapping is unavailable (it is only an annotation)


def test_multi_argument_functions_say_how_the_input_maps_to_arguments() -> None:
    d = build_draft(MODULE, "total", ORIGIN)
    assert any("keyword arguments (items, discount)" in w for w in d.warnings)


@pytest.mark.parametrize("name", ["Box", "missing", "decorated_not_there"])
def test_only_top_level_functions_are_convertible(name: str) -> None:
    with pytest.raises(NotConvertible):
        build_draft(MODULE, name, ORIGIN)


def test_unparsable_files_are_refused() -> None:
    with pytest.raises(NotConvertible):
        build_draft("def broken(:\n", "broken", ORIGIN)


def test_copy_depth_is_capped() -> None:
    chain = (
        "\n".join(f"def f{i}(): return f{i + 1}()" for i in range(30)) + "\ndef f30(): return 1\n"
    )
    d = build_draft(chain, "f0", ORIGIN)
    assert len(d.copied) <= 13 and any("Stopped copying" in w for w in d.warnings)
